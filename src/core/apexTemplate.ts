/** Builds a valid Apex class name `<Flow>_FlowTest`, at most 40 characters. */
export function apexTestClassName(flowName: string): string {
  let base = flowName
    .replace(/[^A-Za-z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!/^[A-Za-z]/.test(base)) base = `F${base}`;
  base = base.slice(0, MAX_CLASS_NAME - CLASS_SUFFIX.length).replace(/_+$/, '');
  return `${base}${CLASS_SUFFIX}`;
}

export function flowKind(flow: FlowMetadata): FlowKind {
  const processType = flow.processType?.toLowerCase();
  if (processType !== 'autolaunchedflow') return 'process';
  const trigger = flow.triggerType;
  if (trigger?.startsWith('Record') && flow.object) return 'record';
  if (trigger === 'PlatformEvent' && flow.object) return 'platformEvent';
  if (trigger === 'Scheduled') return 'scheduled';
  return 'autolaunched';
}

const camel = (name: string): string => {
  const cleaned = name.replace(/__c$|__e$/i, '').replace(/[^A-Za-z0-9]/g, '');
  return cleaned.charAt(0).toLowerCase() + cleaned.slice(1);
};

