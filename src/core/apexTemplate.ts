import { escapeApexString } from './flowXml.js';
import type { RequiredFieldMap } from './requiredFields.js';
import type { FlowFilter, FlowMetadata, FlowVariable } from './types.js';

const MAX_CLASS_NAME = 40;
const CLASS_SUFFIX = '_FlowTest';
const INDENT = '    ';

/** Required fields (with test values) for common standard objects. Custom objects get a TODO. */
const REQUIRED_FIELDS: Record<string, Record<string, string>> = {
  Account: { Name: "'Test Account'" },
  Contact: { LastName: "'Test'" },
  Lead: { LastName: "'Test'", Company: "'Test Company'" },
  Opportunity: { Name: "'Test Opportunity'", StageName: "'Prospecting'", CloseDate: 'Date.today().addDays(30)' },
  Case: { Subject: "'Test Case'" },
  Campaign: { Name: "'Test Campaign'" },
  Product2: { Name: "'Test Product'" },
  Task: { Subject: "'Test Task'" },
  Event: { Subject: "'Test Event'", DurationInMinutes: '30', ActivityDateTime: 'Datetime.now()' },
  Contract: { AccountId: 'null /* TODO: set an Account Id */' },
  Order: { AccountId: 'null /* TODO: set an Account Id */', EffectiveDate: 'Date.today()', Status: "'Draft'" },
};

export type GeneratedApexTest = {
  className: string;
  body: string;
  kind: FlowKind;
};

export type FlowKind = 'record' | 'platformEvent' | 'scheduled' | 'autolaunched' | 'process';

/** Builds a valid Apex class name `<Flow>_FlowTest`, at most 40 characters. */
export function apexTestClassName(flowName: string): string {
  let base = flowName
    .replace(/[^A-Za-z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!/^[A-Za-z]/.test(base)) base = `F${base}`;
  base = base.slice(0, MAX_CLASS_NAME - CLASS_SUFFIX.length).replace(/_+$/, '');
  return `${base}${CLASS_SUFFIX}`;
}

export function flowKind(flow: FlowMetadata): FlowKind {
  const processType = flow.processType?.toLowerCase();
  if (processType !== 'autolaunchedflow') return 'process';
  const trigger = flow.triggerType;
  if (trigger?.startsWith('Record') && flow.object) return 'record';
  if (trigger === 'PlatformEvent' && flow.object) return 'platformEvent';
  if (trigger === 'Scheduled') return 'scheduled';
  return 'autolaunched';
}

const camel = (name: string): string => {
  const cleaned = name.replace(/__c$|__e$/i, '').replace(/[^A-Za-z0-9]/g, '');
  return cleaned.charAt(0).toLowerCase() + cleaned.slice(1);
};

function header(flow: FlowMetadata, description: string): string[] {
  return [
    '/**',
    ` * Starter test generated by sf-flow-coverage for the Flow ${flow.name}${flow.label ? ` (${flow.label})` : ''}.`,
    ` * ${description}`,
    ' * Running this test gives the Flow coverage toward "Deploy processes and flows as active".',
    ' * Replace the TODOs with real data and assertions on what the Flow does.',
    ' */',
    '@IsTest',
  ];
}

function isSimpleField(field: string): boolean {
  return /^[A-Za-z][A-Za-z0-9_]*$/.test(field);
}

/** Entry-criteria fields the generator can set directly (field EqualTo literal). */
function settableCriteria(filters: FlowFilter[]): FlowFilter[] {
  return filters.filter((f) => f.operator === 'EqualTo' && f.apexValue !== undefined && isSimpleField(f.field));
}

function criteriaTodos(flow: FlowMetadata, settable: FlowFilter[]): string[] {
  const todos: string[] = [];
  for (const filter of flow.filters) {
    if (settable.includes(filter)) continue;
    const value = filter.rawValue === undefined ? '' : ` ${filter.rawValue}`;
    todos.push(`// TODO: entry criteria: ${filter.field} ${filter.operator}${value}`);
  }
  if (flow.filterFormula) todos.push(`// TODO: entry criteria formula: ${flow.filterFormula.replace(/\s+/g, ' ')}`);
  if (flow.filterLogic && !['and', 'or'].includes(flow.filterLogic.toLowerCase())) {
    todos.push(`// TODO: entry criteria logic: ${flow.filterLogic}`);
  }
  return todos;
}

/** Described required fields win over the built-in list for standard objects. */
function knownRequired(object: string, required: RequiredFieldMap): Record<string, string> | undefined {
  return required[object] ?? REQUIRED_FIELDS[object];
}

function recordFields(object: string, criteria: FlowFilter[], required: RequiredFieldMap): string[] {
  const fields = new Map<string, string>(Object.entries(knownRequired(object, required) ?? {}));
  for (const filter of criteria) fields.set(filter.field, filter.apexValue as string);
  return [...fields].map(([field, value]) => `${field} = ${value}`);
}

function newRecord(
  object: string,
  variable: string,
  fields: string[],
  indent: string,
  required: RequiredFieldMap,
): string[] {
  const lines: string[] = [];
  if (fields.length === 0) {
    lines.push(`${indent}${object} ${variable} = new ${object}();`);
  } else {
    lines.push(`${indent}${object} ${variable} = new ${object}(`);
    fields.forEach((field, i) => lines.push(`${indent}${INDENT}${field}${i < fields.length - 1 ? ',' : ''}`));
    lines.push(`${indent});`);
  }
  if (!knownRequired(object, required)) lines.push(`${indent}// TODO: set the required fields for ${object}`);
  return lines;
}

function recordMethods(flow: FlowMetadata, required: RequiredFieldMap): string[] {
  const object = flow.object as string;
  // A fixed name avoids Apex reserved words (`case`, `order`, `group`) that object names produce.
  const variable = 'testRecord';
  const settable = settableCriteria(flow.filters);
  const todos = criteriaTodos(flow, settable);
  const i2 = INDENT.repeat(2);
  const requery = (assertion: string): string[] => [
    `${i2}${object} result = [SELECT Id FROM ${object} WHERE Id = :${variable}.Id];`,
    `${i2}// TODO: query and assert the fields this Flow sets`,
    `${i2}${assertion}`,
  ];
  const method = (name: string, body: string[]): string[] => [
    `${INDENT}@IsTest`,
    `${INDENT}static void ${name}() {`,
    ...body,
    `${INDENT}}`,
  ];

  const createBody = (): string[] => [
    ...newRecord(object, variable, recordFields(object, settable, required), i2, required),
    ...todos.map((t) => `${i2}${t}`),
    '',
    `${i2}Test.startTest();`,
    `${i2}insert ${variable};`,
    `${i2}Test.stopTest();`,
    '',
    ...requery(`Assert.isNotNull(result.Id, 'The ${object} should be saved');`),
  ];

  const updateBody = (): string[] => {
    const lines = [
      ...newRecord(object, variable, recordFields(object, [], required), i2, required),
      `${i2}insert ${variable};`,
      '',
      `${i2}Test.startTest();`,
    ];
    for (const filter of settable) lines.push(`${i2}${variable}.${filter.field} = ${filter.apexValue};`);
    lines.push(...todos.map((t) => `${i2}${t}`));
    if (settable.length === 0 && todos.length === 0) lines.push(`${i2}// TODO: change the fields this Flow reacts to`);
    lines.push(`${i2}update ${variable};`, `${i2}Test.stopTest();`, '');
    return [...lines, ...requery(`Assert.isNotNull(result.Id, 'The ${object} should still exist');`)];
  };

  const deleteBody = (): string[] => [
    ...newRecord(object, variable, recordFields(object, settable, required), i2, required),
    ...todos.map((t) => `${i2}${t}`),
    `${i2}insert ${variable};`,
    '',
    `${i2}Test.startTest();`,
    `${i2}delete ${variable};`,
    `${i2}Test.stopTest();`,
    '',
    `${i2}// TODO: assert what this Flow does when the record is deleted`,
    `${i2}Assert.areEqual(0, [SELECT COUNT() FROM ${object} WHERE Id = :${variable}.Id], 'The ${object} should be deleted');`,
  ];

  switch (flow.recordTriggerType) {
    case 'Update':
      return method('runsFlowOnUpdate', updateBody());
    case 'CreateAndUpdate':
      return [...method('runsFlowOnCreate', createBody()), '', ...method('runsFlowOnUpdate', updateBody())];
    case 'Delete':
      return method('runsFlowOnDelete', deleteBody());
    default:
      return method('runsFlowOnCreate', createBody());
  }
}

function inputValue(variable: FlowVariable): string {
  if (variable.isCollection) {
    const element: Record<string, string> = {
      String: 'String',
      Picklist: 'String',
      Multipicklist: 'String',
      Boolean: 'Boolean',
      Number: 'Decimal',
      Currency: 'Decimal',
      Date: 'Date',
      DateTime: 'Datetime',
    };
    if (variable.dataType === 'SObject' && variable.objectType) return `new List<${variable.objectType}>()`;
    if (element[variable.dataType]) return `new List<${element[variable.dataType]}>()`;
    return 'null';
  }
  switch (variable.dataType) {
    case 'String':
    case 'Picklist':
    case 'Multipicklist':
      return "'test'";
    case 'Boolean':
      return 'false';
    case 'Number':
    case 'Currency':
      return '0';
    case 'Date':
      return 'Date.today()';
    case 'DateTime':
      return 'Datetime.now()';
    default:
      return 'null';
  }
}

function interviewMethod(flow: FlowMetadata, name: string, notes: string[], required: RequiredFieldMap): string[] {
  const i2 = INDENT.repeat(2);
  const lines = [`${INDENT}@IsTest`, `${INDENT}static void ${name}() {`, ...notes.map((n) => `${i2}// ${n}`)];
  lines.push(`${i2}Map<String, Object> inputs = new Map<String, Object>();`);
  for (const variable of flow.variables.filter((v) => v.isInput)) {
    if (variable.dataType === 'SObject' && variable.objectType && !variable.isCollection) {
      const local = `${camel(variable.name) || 'input'}Input`;
      lines.push(
        ...newRecord(variable.objectType, local, recordFields(variable.objectType, [], required), i2, required),
      );
      lines.push(`${i2}insert ${local};`, `${i2}inputs.put('${escapeApexString(variable.name)}', ${local});`);
    } else {
      const type = variable.apexClass ?? variable.objectType ?? variable.dataType;
      lines.push(
        `${i2}inputs.put('${escapeApexString(variable.name)}', ${inputValue(variable)}); // TODO: ${type}${variable.isCollection ? ' collection' : ''}`,
      );
    }
  }
  lines.push(
    '',
    `${i2}Test.startTest();`,
    `${i2}Flow.Interview interview = Flow.Interview.createInterview('${escapeApexString(flow.name)}', inputs);`,
    `${i2}interview.start();`,
    `${i2}Test.stopTest();`,
    '',
    `${i2}// TODO: assert what this Flow does`,
  );
  for (const variable of flow.variables.filter((v) => v.isOutput)) {
    lines.push(
      `${i2}Object ${camel(variable.name) || 'output'}Output = interview.getVariableValue('${escapeApexString(variable.name)}');`,
    );
  }
  lines.push(`${i2}Assert.isNotNull(interview, 'The Flow interview should run');`, `${INDENT}}`);
  return lines;
}

function platformEventMethod(flow: FlowMetadata, required: RequiredFieldMap): string[] {
  const event = flow.object as string;
  const i2 = INDENT.repeat(2);
  const settable = settableCriteria(flow.filters);
  return [
    `${INDENT}@IsTest`,
    `${INDENT}static void runsFlowOnEvent() {`,
    ...newRecord(event, 'testEvent', recordFields(event, settable, required), i2, required).filter(
      (l) => !l.includes('TODO: set the required'),
    ),
    `${i2}// TODO: set the event fields this Flow reads`,
    ...criteriaTodos(flow, settable).map((t) => `${i2}${t}`),
    '',
    `${i2}Test.startTest();`,
    `${i2}EventBus.publish(testEvent);`,
    `${i2}Test.getEventBus().deliver();`,
    `${i2}Test.stopTest();`,
    '',
    `${i2}// TODO: assert what this Flow does when the event is delivered`,
    `${i2}Assert.isNotNull(testEvent, 'The event should be published');`,
    `${INDENT}}`,
  ];
}

function processMethod(flow: FlowMetadata): string[] {
  const i2 = INDENT.repeat(2);
  return [
    `${INDENT}@IsTest`,
    `${INDENT}static void runsProcess() {`,
    `${i2}// TODO: ${flow.processType ?? 'This'} processes start when a record changes or an event fires.`,
    `${i2}// Insert or update a record that meets this process's criteria between startTest and stopTest.`,
    `${i2}Test.startTest();`,
    `${i2}Test.stopTest();`,
    '',
    `${i2}// TODO: assert what this process does`,
    `${i2}Assert.isTrue(true, 'Replace with real assertions');`,
    `${INDENT}}`,
  ];
}

export type GenerateOptions = {
  /** Required fields per object from an org describe. Falls back to a built-in list for common standard objects. */
  requiredFields?: RequiredFieldMap;
};

/** Generates a starter Apex test class for a Flow from its metadata. */
export function generateApexTest(flow: FlowMetadata, options: GenerateOptions = {}): GeneratedApexTest {
  const required = options.requiredFields ?? {};
  const className = apexTestClassName(flow.name);
  const kind = flowKind(flow);
  let description: string;
  let methods: string[];

  switch (kind) {
    case 'record':
      description = `Record-triggered on ${flow.object} (${flow.recordTriggerType ?? 'Create'}, ${flow.triggerType}).`;
      methods = recordMethods(flow, required);
      break;
    case 'platformEvent':
      description = `Triggered by the platform event ${flow.object}.`;
      methods = platformEventMethod(flow, required);
      break;
    case 'scheduled':
      description = 'Schedule-triggered. Apex tests cannot fire the schedule, so this test starts the Flow directly.';
      methods = interviewMethod(
        flow,
        'runsFlow',
        [
          flow.object
            ? `TODO: this Flow runs for ${flow.object} records on a schedule; $Record is not set when started from Apex.`
            : 'TODO: this Flow runs on a schedule; it is started directly here.',
          'If the Flow depends on $Record, move its logic to an autolaunched subflow and test that instead.',
        ],
        required,
      );
      break;
    case 'autolaunched':
      description = 'Autolaunched (no trigger).';
      methods = interviewMethod(flow, 'runsFlow', [], required);
      break;
    default:
      description = `Process type ${flow.processType ?? 'unknown'}.`;
      methods = processMethod(flow);
  }

  const body = [...header(flow, description), `private class ${className} {`, ...methods, '}', ''].join('\n');
  return { className, body, kind };
}

export function apexClassMetaXml(apiVersion: string): string {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<ApexClass xmlns="http://soap.sforce.com/2006/04/metadata">',
    `    <apiVersion>${apiVersion}</apiVersion>`,
    '    <status>Active</status>',
    '</ApexClass>',
    '',
  ].join('\n');
}
