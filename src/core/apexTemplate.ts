/** Field values from the org describe that the criteria solver can draw on. */
type CriteriaValues = {
  /** A value per settable field, including lookup Ids. */
  fieldValues: RequiredFieldMap;
  /** A value per field that differs from the insert value, for `IsChanged true`. */
  changedValues: RequiredFieldMap;
  /** What a new record holds in each field the test doesn't set, for following the Flow's decisions. */
  unsetValues: Record<string, Record<string, string | null>>;
  /** Lookup field per relationship name, per object. */
  relationships: Record<string, Record<string, string>>;
  /** The object each lookup field points to, per object. */
  lookups: Record<string, Record<string, string>>;
  /** Fields the criteria need on parent records, per parent object; filled while generating. */
  parentFields: Map<string, Map<string, string>>;
  /** Fields a test can't set at all, per object. */
  readOnlyFields: Record<string, string[]>;
  /** Fields a test can set on insert but not change in an update, per object. */
  createOnlyFields: Record<string, string[]>;
  /** Active picklist values per field, per object. */
  picklists: Record<string, Record<string, PicklistInfo>>;
  /** Active validation rules per object. */
  validationRules: Record<string, ValidationRule[]>;
  /** Required lookup filters per object. */
  lookupFilters: Record<string, LookupFilter[]>;
};

/** What the criteria solver knows about the record an insert or an update test builds. */
function criteriaContext(
  object: string,
  values: CriteriaValues,
  required: RequiredFieldMap,
  context: 'insert' | 'update',
): SolveContext {
  return {
    object,
    context,
    inserted: knownRequired(object, required) ?? {},
    fieldValues: values.fieldValues[object] ?? {},
    changedValues: values.changedValues[object] ?? {},
    relationships: values.relationships[object] ?? {},
    lookups: values.lookups[object] ?? {},
    parentFieldValues: (parent) => values.fieldValues[parent] ?? {},
    normalize: (target, field, apex) => {
      const picklist = values.picklists[target]?.[field];
      const known = knownOf(apex);
      if (!picklist || known.kind !== 'string') return apex;
      const match = picklist.values.find((v) => v.toLowerCase() === known.value.toLowerCase());
      if (match !== undefined) return `'${escapeApexString(match)}'`;
      return picklist.restricted ? null : apex;
    },
    writable: (target, field, when) =>
      !values.readOnlyFields[target]?.includes(field) &&
      (when === 'insert' || !values.createOnlyFields[target]?.includes(field)),
  };
}

/** Plans field values that meet the Flow's entry criteria for an insert or an update test. */
function planCriteria(
  flow: FlowMetadata,
  object: string,
  values: CriteriaValues,
  required: RequiredFieldMap,
  context: 'insert' | 'update',
): CriteriaPlan {
  let plan = solveCriteria(entryCondition(flow), criteriaContext(object, values, required, context));
  if (context === 'update') {
    // The insert has to pass the rules too: check it on the values the insert sets.
    const insert = withValidation({ ...emptyPlan(), set: new Map(plan.prior) }, object, values, required, 'insert');
    plan = { ...plan, prior: insert.set, unmet: [...plan.unmet, ...insert.unmet] };
  }
  plan = withValidation(plan, object, values, required, context);
  for (const [parent, fields] of plan.parents) {
    const known = values.parentFields.get(parent) ?? new Map<string, string>();
    for (const [field, value] of fields) if (!known.has(field)) known.set(field, value);
    values.parentFields.set(parent, known);
  }
  return plan;
}

const criteriaTodos = (plan: CriteriaPlan): string[] => plan.unmet.map((u) => `// TODO: ${u.label}: ${u.text}`);

const emptyPlan = (): CriteriaPlan => ({
  set: new Map(),
  prior: new Map(),
  keep: new Set(),
  parents: new Map(),
  unmet: [],
});

/**
 * Makes a plan's values pass the object's validation rules and lookup filters for one save. A
 * rule certain not to fire is left alone. For any other rule, the plan also meets the rule's
 * opposite when it can do so without new TODOs; a rule certain to block the save that it can't
 * avoid becomes a TODO. A lookup filter applies when the record looks up a parent the test
 * inserts: the parent (or the record) gets the values the filter needs, or the filter becomes a TODO.
 */
function withValidation(
  plan: CriteriaPlan,
  object: string,
  values: CriteriaValues,
  required: RequiredFieldMap,
  save: 'insert' | 'update',
): CriteriaPlan {
  const rules = values.validationRules[object] ?? [];
  const filters = values.lookupFilters[object] ?? [];
  if (rules.length === 0 && filters.length === 0) return plan;
  const ctx = criteriaContext(object, values, required, save);
  const unset = values.unsetValues[object] ?? {};
  const stateOf = (current: CriteriaPlan): FieldState => {
    if (save === 'insert') return fieldState(recordFieldValues(object, current.set, required), unset);
    const inserted = recordFieldValues(object, current.prior, required);
    const after = new Map([...inserted, ...current.set]);
    return fieldState(after, unset, new Set(), inserted);
  };
  let current = plan;
  for (const rule of rules) {
    const condition = conditionFromValidationRule(rule.formula, save);
    const state = stateOf(current);
    const blocks = evaluateCondition(condition, { get: (reference) => state.get(reference) });
    if (blocks === false) continue;
    const avoided = solveCriteria(negate(condition), ctx, current);
    if (avoided.unmet.length === current.unmet.length) {
      current = avoided;
    } else if (blocks) {
      const text = rule.message ? `${rule.name} (${rule.message.replace(/\s+/g, ' ')})` : rule.name;
      current = { ...current, unmet: [...current.unmet, { label: 'validation rule', text }] };
    }
  }
  const inserted = knownRequired(object, required) ?? {};
  for (const filter of filters) {
    const relationship = Object.entries(values.relationships[object] ?? {}).find(
      ([, field]) => field === filter.lookup,
    )?.[0];
    const lookup =
      current.set.get(filter.lookup) ??
      (save === 'update' ? current.prior.get(filter.lookup) : undefined) ??
      inserted[filter.lookup];
    // The filter only checks a lookup that's filled, and the test can only shape a parent it inserts.
    if (!relationship || !lookup || !/Parent\.Id$/.test(lookup)) continue;
    const met = solveCriteria(conditionFromLookupFilter(filter, relationship), ctx, current);
    if (met.unmet.length === current.unmet.length) {
      current = met;
    } else {
      const message = filter.errorMessage ? ` (${filter.errorMessage.replace(/\s+/g, ' ')})` : '';
      current = {
        ...current,
        unmet: [...current.unmet, { label: 'lookup filter', text: `${filter.lookup}${message}` }],
      };
    }
  }
  return current;
}

/** Fields a record inserted only to support the test (a parent, an input) needs to pass its object's rules. */
function validInsertFields(
  object: string,
  overrides: Map<string, string>,
  values: CriteriaValues,
  required: RequiredFieldMap,
): Map<string, string> {
  const plan = withValidation({ ...emptyPlan(), set: new Map(overrides) }, object, values, required, 'insert');
  // Fields its own lookup filters need on its parents (the test's grandparents).
  for (const [parent, fields] of plan.parents) {
    const known = values.parentFields.get(parent) ?? new Map<string, string>();
    for (const [field, value] of fields) if (!known.has(field)) known.set(field, value);
    values.parentFields.set(parent, known);
  }
  return plan.set;
}

/** Described required fields win over the built-in list for standard objects. */
function knownRequired(object: string, required: RequiredFieldMap): Record<string, string> | undefined {
  return required[object] ?? REQUIRED_FIELDS[object];
}

function recordFieldValues(
  object: string,
  criteria: Map<string, string>,
  required: RequiredFieldMap,
): Map<string, string> {
  const fields = new Map<string, string>(Object.entries(knownRequired(object, required) ?? {}));
  for (const [field, value] of criteria) fields.set(field, value);
  return fields;
}

function recordFields(object: string, criteria: Map<string, string>, required: RequiredFieldMap): string[] {
  return [...recordFieldValues(object, criteria, required)].map(([field, value]) => `${field} = ${value}`);
}

/**
 * What the test knows about the record's fields when the Flow runs: the values it sets, what the
 * describe says a new record holds in the fields it doesn't set (except `unknown` fields), and,
 * in an update, the values before it (`$Record__Prior`).
 */
function fieldState(
  values: Map<string, string>,
  unset: Record<string, string | null>,
  unknown: Set<string> = new Set(),
  prior?: Map<string, string>,
): FieldState {
  const state: FieldState = new Map();
  for (const [field, value] of Object.entries(unset)) {
    if (!unknown.has(field)) state.set(`$Record.${field}`, value);
  }
  // `null /* TODO: set a ... Id */` leaves the field empty.
  const apex = (value: string): string | null => (/^null\b/.test(value) ? null : value);
  for (const [field, value] of values) state.set(`$Record.${field}`, apex(value));
  if (prior) {
    for (const [field, value] of Object.entries(unset)) state.set(`$Record__Prior.${field}`, value);
    for (const [field, value] of prior) state.set(`$Record__Prior.${field}`, apex(value));
  }
  return state;
}

